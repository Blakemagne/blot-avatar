const half = [.4,.4,.55];
const cache = new WeakMap<CoatMesh, WeakMap<readonly number[], CoatMesh>>();

export function fittedRim(source: CoatMesh, frame: readonly number[], kind: 'Monocle' | 'Tall oval frames', side: number): CoatMesh {
  if (frame[0] === 1 && frame[4] === 1 && frame[6] === 0) return source;
  let mounts = cache.get(source);
  if (!mounts) cache.set(source, mounts = new WeakMap());
  const saved = mounts.get(frame);
  if (saved) return saved;

  const ring = kind === 'Monocle';
  const model = ring ? monocle : side < 0 ? leftOval : rightOval;
  const terms = [
    ring ? frame[1] : side < 0 ? frame[5] : frame[3],
    ring ? frame[7] : side < 0 ? frame[6] : frame[5],
    (frame[0] - 1) ** 2,
    frame[6] ** 2,
  ];
  const amount = model.modes.map((_, i) =>
    terms.reduce((sum, value, j) => sum + value * model.response[j][i], 0));
  const coefficients = model.modes[0].map((_, i) =>
    model.modes.reduce((sum, mode, j) => sum + amount[j] * mode[i], 0));
  // The fitted displacements act in donor coordinates before the frame mount.
  // Restore the identity part of the normalized affine basis.
  for (let i = 0; i < 3; i++) {
    coefficients[i] += model.mid[i];
    coefficients[3 + 4*i] += half[i];
  }
  const mesh = fittedMesh(source, { mesh: kind, mid: model.mid, half,
    coefficients, kernels: model.kernels, falloff: 2 });
  mounts.set(frame, mesh);
  return mesh;
}
